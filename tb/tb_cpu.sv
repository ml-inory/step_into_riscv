//============================================================================
// tb_cpu.sv - self-checking testbench for the single-cycle RV32I CPU
//
// Loads tb/program.S (assembled to instr_mem.hex) into the instruction
// memory, runs the CPU until it parks on its final `jal x0, done`, then
// compares the whole register file against the expected architectural
// state and dumps everything.
//
// Exit status is non-zero on failure ($fatal), so it works in CI.
//
// This testbench looks inside the DUT (hierarchical references) to read the
// register file, the data memory and the instruction memory.  It therefore
// depends on these instance names inside `CPU`:
//     u_reg_file.reg_array    u_data_mem.reg_array    u_instr_mem.mem
//
//   python sim/run_tb.py          # build + run
//   python sim/run_tb.py --trace  # per-cycle pc / instruction trace
//============================================================================
`timescale 1ns/1ps

module tb_cpu;

    // ------------------------------------------------------------------
    // parameters
    // ------------------------------------------------------------------
    localparam int CLK_PERIOD  = 10;    // ns
    localparam int MAX_CYCLES  = 400;   // hard cap on the run
    localparam int STALL_LIMIT = 4;     // "pc unchanged" cycles => parked
    localparam int MIN_CYCLES  = 10;    // don't call it parked before this

    // ------------------------------------------------------------------
    // clock / reset
    // ------------------------------------------------------------------
    logic clk   = 1'b0;
    logic rst_n = 1'b0;

    always #(CLK_PERIOD / 2) clk = ~clk;

    // ------------------------------------------------------------------
    // DUT
    // ------------------------------------------------------------------
    CPU dut (
        .clk   (clk),
        .rst_n (rst_n)
    );

    // ------------------------------------------------------------------
    // bookkeeping
    // ------------------------------------------------------------------
    int errors     = 0;
    int cycles     = 0;
    bit parked     = 0;
    bit trace_on   = 0;
    logic [31:0] prev_pc = 32'hxxxx_xxxx;
    int stall      = 0;

    // ------------------------------------------------------------------
    // expected architectural state, generated by tb/asm.py from the
    // program's own `// expect xN = value` directives.  Registers with no
    // directive are 0.  The testbench compares all 32, so a stray write
    // anywhere is caught.
    // ------------------------------------------------------------------
    logic [31:0] exp_reg [0:31];

    initial $readmemh("expected.hex", exp_reg);

    // ------------------------------------------------------------------
    // load the program (mirrors InstrMem's own $readmemh so the test still
    // works if that one moves)
    // ------------------------------------------------------------------
    initial $readmemh("instr_mem.hex", dut.u_instr_mem.mem);

    // ------------------------------------------------------------------
    // helpers
    // ------------------------------------------------------------------
    // Portable "has X/Z" test: for a fully known vector v^v == 0, otherwise
    // the result is X.  ($isunknown() is not implemented by Icarus.)
    function automatic bit is_unknown(input logic [31:0] v);
        return ((v ^ v) !== 32'b0);
    endfunction

    // Sanity: $readmemh leaves the array untouched (all X) when the file is
    // missing, which would otherwise show up as 32 mysterious FAIL lines.
    task automatic check_expected_loaded;
        if (is_unknown(exp_reg[0]) && is_unknown(exp_reg[31])) begin
            $display("  FAIL  expected.hex was not loaded");
            $display("        (tb/asm.py generates it next to instr_mem.hex)");
            errors++;
        end
    endtask

    task automatic check_reg(input int idx, input logic [31:0] expected);
        logic [31:0] got;
        got = dut.u_reg_file.reg_array[idx];
        if (got === expected) begin
            $display("  PASS  x%-2d = 0x%08h  (%0d)", idx, got, $signed(got));
        end else begin
            errors++;
            $display("  FAIL  x%-2d = 0x%08h  expected 0x%08h",
                     idx, got, expected);
        end
    endtask

    task automatic dump_regfile;
        $display("  final register file:");
        for (int r = 0; r < 32; r += 4) begin
            $display("    x%-2d=0x%08h  x%-2d=0x%08h  x%-2d=0x%08h  x%-2d=0x%08h",
                     r,   dut.u_reg_file.reg_array[r],
                     r+1, dut.u_reg_file.reg_array[r+1],
                     r+2, dut.u_reg_file.reg_array[r+2],
                     r+3, dut.u_reg_file.reg_array[r+3]);
        end
    endtask

    task automatic dump_mem;
        // Program agnostic: list whatever is non-zero in the first 32 words.
        // Informational only - stores are already proven by the `lw`
        // read-back that the program's own expectations check.
        int shown = 0;
        $display("  data memory (first non-zero words):");
        for (int w = 0; w < 256; w++) begin
            if (dut.u_data_mem.reg_array[w] !== 32'b0 && shown < 8) begin
                $display("    word[%0d] = 0x%08h", w,
                         dut.u_data_mem.reg_array[w]);
                shown++;
            end
        end
        if (shown == 0)
            $display("    (all zero - this program does not touch data memory)");
    endtask

    // ------------------------------------------------------------------
    // main sequence
    // ------------------------------------------------------------------
    initial begin
        if ($test$plusargs("trace")) trace_on = 1;

        check_expected_loaded();

        $display("");
        $display("================================================================");
        $display(" tb_cpu : single-cycle RV32I CPU");
        $display("================================================================");

        // ---- reset ----
        rst_n = 1'b0;
        repeat (3) @(posedge clk);
        #1 rst_n = 1'b1;

        // ---- sanity: did the program actually load? ----
        if (dut.u_instr_mem.mem[0] !== 8'h93 || dut.u_instr_mem.mem[3] !== 8'h00) begin
            $display("  FAIL  instruction memory was not loaded (instr_mem.hex?)");
            $display("        mem[0..3] = %02h %02h %02h %02h",
                     dut.u_instr_mem.mem[0], dut.u_instr_mem.mem[1],
                     dut.u_instr_mem.mem[2], dut.u_instr_mem.mem[3]);
            errors++;
        end else begin
            $display("  program loaded: first word = %02h%02h%02h%02h",
                     dut.u_instr_mem.mem[3], dut.u_instr_mem.mem[2],
                     dut.u_instr_mem.mem[1], dut.u_instr_mem.mem[0]);
        end

        // ---- run until the CPU parks or we run out of patience ----
        // NOTE: no `break` here - Icarus does not implement it.
        prev_pc = 32'hxxxx_xxxx;
        stall   = 0;
        cycles  = 0;
        parked  = 0;
        while (!parked && cycles < MAX_CYCLES) begin
            @(posedge clk);
            #1;
            cycles++;

            if (trace_on)
                $display("  [%0d] pc=0x%08h instr=0x%08h",
                         cycles, dut.pc, dut.instr);

            if (dut.pc === prev_pc) begin
                stall++;
            end else begin
                stall   = 0;
                prev_pc = dut.pc;
            end

            if (stall >= STALL_LIMIT && cycles >= MIN_CYCLES)
                parked = 1;
        end

        $display("");
        if (parked)
            $display("  CPU parked at pc=0x%08h after %0d cycles", dut.pc, cycles);
        else begin
            $display("  FAIL  CPU never parked - still running after %0d cycles (pc=0x%08h)",
                     cycles, dut.pc);
            errors++;
        end

        // ---- compare the register file ----
        $display("");
        $display("  ---- register checks ----");
        check_reg(0, 32'h0000_0000);
        for (int r = 1; r < 32; r++) check_reg(r, exp_reg[r]);

        // ---- memory side effects ----
        $display("");
        $display("  ---- data memory ----");
        dump_mem;

        // ---- summary ----
        $display("");
        dump_regfile;
        $display("");
        $display("================================================================");
        if (errors == 0) begin
            $display(" RESULT: PASS  (%0d cycles)", cycles);
            $display("================================================================");
            $finish;
        end else begin
            $display(" RESULT: FAIL  (%0d checks failed, %0d cycles)",
                     errors, cycles);
            $display("================================================================");
            $fatal(1, "tb_cpu failed");
        end
    end

    // watchdog
    initial begin
        #(CLK_PERIOD * (MAX_CYCLES + 50));
        $display("  FATAL: watchdog timeout");
        $fatal(1, "watchdog");
    end

endmodule
