//============================================================================
// program_sum.S - 计算 1 + 2 + 3 + ... + 10
//
//   x1 = sum   累加结果（应为 55）
//   x2 = i     循环变量（退出时为 11）
//   x3 = 10    循环上界
//
// 循环体:  sum += i;  i++;  if (i <= 10) 继续;
//
// 汇编 + 仿真:
//   python sim/run_tb.py --program tb/program_sum.S
//============================================================================

_start:
        addi    x1, x0, 0           // sum = 0
        addi    x2, x0, 1           // i   = 1
        addi    x3, x0, 10          // n   = 10

loop:
        add     x1, x1, x2          // sum += i
        addi    x2, x2, 1           // i++
        bge     x3, x2, loop        // 10 >= i ? 继续循环

done:
        jal     x0, done            // 原地停机

// 期望的最终寄存器状态（testbench 据此逐项比对）
// expect x1 = 55        ; 1+2+...+10
// expect x2 = 11        ; i 自增到 11 后循环退出
// expect x3 = 10
